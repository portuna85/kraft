package com.kraft.report.domain;

/**
 * 신고의 처리 상태.
 * <p>
 * 처리한 뒤에도 행을 남기는 것이 중요하다 — 같은 대상이 반복해서 신고되는지, 관리자가 무엇을
 * 언제 지웠는지가 남아야 나중에 설명할 수 있다.
 */
public enum ReportStatus {

    /** 아직 관리자가 보지 않았다. 관리자 화면의 기본 목록이다. */
    PENDING,

    /** 문제가 없다고 판단했다. 대상은 그대로 둔다. */
    REJECTED,

    /** 신고를 받아들여 대상을 삭제했다. */
    RESOLVED,

    /**
     * 관리자가 판단하기 전에 작성자 본인이 대상을 스스로 지워 사라졌다(개선 보고서 A-BE-01).
     * {@link #RESOLVED}와 구분하는 이유는 "관리자가 지웠다"와 "작성자가 스스로 지웠다"가
     * 기록상 다른 사실이기 때문이다 — 후자는 신고 접수 시점의 스냅샷(target_*_snapshot)이
     * 유일한 근거로 남는다.
     */
    TARGET_DELETED
}
